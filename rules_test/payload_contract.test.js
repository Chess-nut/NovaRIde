// The payloads the Dart app actually sends, against the real ruleset.
//
// Every other test in this directory uses a fixture somebody typed here.
// That proves the rules are right about *a* payload — not about the one
// FirebaseAuthRepository sends. A field the app omits and the rules
// require would pass all of them and fail at sign-up, for real, on a
// phone.
//
// So the payloads in fixtures/auth_payloads.json are written by
// `flutter test test/auth_payload_contract_test.dart`, straight out of
// the production builders on FirebaseAuthRepository. This file replays
// them through the same transaction ensureProfile runs.
//
// **Run `flutter test` before `npm test`.** The fixture is committed, so
// it is usually current and a change to it shows up in review; the check
// below is what catches the case where it is not there at all.

import { existsSync, readFileSync } from 'node:fs';
import { after, before, beforeEach, describe, it } from 'node:test';
import { assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import {
  doc, getDoc, runTransaction, serverTimestamp, setDoc, Timestamp,
} from 'firebase/firestore';
import { asGuardian, asRider, newTestEnv, reset } from './helpers.js';

const FIXTURE = new URL('./fixtures/auth_payloads.json', import.meta.url);

if (!existsSync(FIXTURE)) {
  throw new Error(
    'rules_test/fixtures/auth_payloads.json is missing. It is generated by\n' +
    '  flutter test test/auth_payload_contract_test.dart\n' +
    'Run that first — these tests are meaningless without it, and passing\n' +
    'them without it would be worse than failing.',
  );
}

const payloads = JSON.parse(readFileSync(FIXTURE, 'utf8'));

/// Turns the exported marker back into a real server timestamp. Anything
/// else passes through as written.
const revive = (payload) => Object.fromEntries(
  Object.entries(payload).map(
    ([key, value]) =>
      [key, value === '__SERVER_TIMESTAMP__' ? serverTimestamp() : value],
  ),
);

const ownerPermissions = {
  liveLocation: true,
  emergencyAlerts: true,
  tripStatus: true,
  helmetStatus: true,
  incidentHistory: true,
};

const riderSignup = (db, user, { includeFamilyId = true } = {}) => runTransaction(db, async (tx) => {
  const userRef = doc(db, 'users', payloads.riderUid);
  const claimRef = doc(db, 'usernames', payloads.usernameLower);
  await tx.get(userRef);
  await tx.get(claimRef);
  tx.set(userRef, includeFamilyId
    ? { ...user, familyId: payloads.riderUid }
    : user);
  tx.set(doc(db, 'riderProfiles', payloads.riderUid), revive(payloads.profile));
  tx.set(doc(db, 'families', payloads.riderUid), {
    ownerUid: payloads.riderUid,
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp(),
  });
  tx.set(doc(db, 'families', payloads.riderUid, 'members', payloads.riderUid),
    {
      uid: payloads.riderUid,
      role: 'rider',
      status: 'active',
      permissions: ownerPermissions,
      displayName: user.fullName || 'Rider One',
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp(),
    });
  tx.set(claimRef, revive(payloads.usernameClaim));
});

let env;
before(async () => { env = await newTestEnv(); });
after(async () => { await env.cleanup(); });
beforeEach(async () => { await reset(env); });

describe('the payloads FirebaseAuthRepository sends', () => {
  // The ids in the fixture have to be the ones these contexts sign in
  // as, or every rule here fails for the wrong reason.
  it('were exported for the uids these tests use', () => {
    if (payloads.riderUid !== 'uid-mobile-rider'
      || payloads.riderEmail !== 'rider@example.test') {
      throw new Error(
        `The fixture was exported for ${payloads.riderUid} / ` +
        `${payloads.riderEmail}, which is not who asRider() signs in as. ` +
        'Keep test/auth_payload_contract_test.dart and helpers.js in step.',
      );
    }
  });

  // The whole of sign-up, as one transaction, with the real maps. This
  // is the test that would have caught a missing fullName.
  it('are accepted as a sign-up transaction', async () => {
    const db = asRider(env);
    await assertSucceeds(riderSignup(db, revive(payloads.user)));

    // And the documents are really there afterwards, with the field the
    // guardian dashboards need during an SOS.
    const written = await getDoc(doc(asRider(env), 'users', payloads.riderUid));
    if (written.data().fullName !== 'Rider One') {
      throw new Error('users/ landed without a usable fullName.');
    }
  });

  it('refuses the current rider payload without the required familyId', async () => {
    await assertFails(riderSignup(asRider(env), revive(payloads.user), {
      includeFamilyId: false,
    }));
  });

  it('are accepted for a guardian too', async () => {
    const db = asGuardian(env);
    await assertSucceeds(runTransaction(db, async (tx) => {
      const userRef = doc(db, 'users', payloads.guardianUid);
      await tx.get(userRef);
      tx.set(userRef, revive(payloads.guardianUser));
      tx.set(doc(db, 'guardianProfiles', payloads.guardianUid),
        revive(payloads.profile));
    }));
  });

  it('are accepted as the sign-in touch, with and without a push token',
    async () => {
      for (const key of ['loginTouch', 'loginTouchNoToken']) {
        await reset(env);
        await env.withSecurityRulesDisabled(async (context) => {
          await setDoc(
            doc(context.firestore(), 'users', payloads.riderUid),
            { ...payloads.user, familyId: payloads.riderUid, createdAt: Timestamp.now(),
              updatedAt: Timestamp.now(), lastLoginAt: Timestamp.now() },
          );
        });

        const db = asRider(env);
        await assertSucceeds(runTransaction(db, async (tx) => {
          const userRef = doc(db, 'users', payloads.riderUid);
          await tx.get(userRef);
          tx.update(userRef, revive(payloads[key]));
        }));
      }
    });

  // Proof that the test can fail: the same transaction with fullName
  // removed is refused. Without this, a rule that stopped checking
  // anything would leave every case above passing.
  it('would be refused if the app stopped sending fullName', async () => {
    const withoutFullName = { ...payloads.user };
    delete withoutFullName.fullName;

    const db = asRider(env);
    await assertFails(riderSignup(db, revive(withoutFullName)));
  });
});

// Proof that the harness is not lying about timestamps.
//
// The fixture carries server timestamps as the string
// `__SERVER_TIMESTAMP__`, and revive() swaps it for a real
// serverTimestamp() sentinel. If that swap ever stopped happening, every
// test above would still send *something* for createdAt — and would be
// green on a payload that is not what ships. That is the exact shape of
// gap this file exists to close, so it is worth one case of its own.
describe('the server-timestamp marker', () => {
  it('is refused by the rules when it reaches them unrevived', async () => {
    const db = asRider(env);
    // Deliberately not revived: the raw string goes to Firestore.
    await assertFails(riderSignup(db, payloads.user));
  });

  // And the same payload with the swap applied is accepted, which is
  // what makes the case above meaningful rather than merely true.
  it('is accepted once revived', async () => {
    const db = asRider(env);
    await assertSucceeds(riderSignup(db, revive(payloads.user)));
  });

  it('really does produce a timestamp, not a string', async () => {
    const db = asRider(env);
    await riderSignup(db, revive(payloads.user));
    const written = await getDoc(doc(asRider(env), 'users', payloads.riderUid));
    const createdAt = written.data().createdAt;
    if (!(createdAt instanceof Timestamp)) {
      throw new Error(
        `createdAt landed as ${typeof createdAt} (${createdAt}), not a ` +
        'Timestamp. revive() is not doing its job and every other case ' +
        'in this file is worthless.',
      );
    }
  });
});
